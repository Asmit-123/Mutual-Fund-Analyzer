import re
from langchain_openai import ChatOpenAI
from graph.state import AgentState
from dotenv import load_dotenv
load_dotenv()

llm = ChatOpenAI(model="gpt-4o", temperature=0.1)

SYNTH_PROMPT = """
You are a professional financial report designer and formatter.
Your job is to take the provided mutual fund ranking and analysis and format it into a stunning, executive-ready HTML document suitable for a PDF report.

Rules for HTML Formatting:
- Return ONLY valid HTML — no markdown, no code fences (e.g., no ```html), no conversational filler, no explanations.
- Use semantic HTML with inline styling for a clean, modern, highly professional aesthetic.
- Include a bold, clear main report title (e.g., <h1>Mutual Fund AI Ranking Report</h1>).
- Structure the content logically:
    - Use <h2> for main sections (e.g., "Fund Rankings", "Market Capture Analysis", "Executive Summary").
    - Use a well-designed HTML <table> with a clean border and distinct header row for the funds and their capture ratios (Up/Down/Overall).
    - Use clear spacing, bullet points, or numbered lists for the rankings and the AI's justifications.
- Do NOT invent any new financial data; strictly format and organize the information provided in the input text.
- Add a professional disclaimer at the very bottom in small italics: 
  "Disclaimer: Past performance is not indicative of future returns. This report is generated by AI based on AdvisorKhoj Market Capture Ratio data and is for informational purposes only, not personalized investment advice."
"""

def clean_html_output(text: str) -> str:
    """Removes markdown code blocks if the LLM accidentally includes them."""
    text = text.strip()
    text = re.sub(r"^```(?:html)?\s*", "", text, flags=re.IGNORECASE)
    text = re.sub(r"\s*```$", "", text)
    return text.strip()

def synthesizer_node(state: AgentState) -> dict:
    print("Executing synthesizer_node to build final PDF report...")

    tool_results = state.get("tool_results", {})
    
    # Grab the raw analysis generated by the fund_info node
    raw_report_data = tool_results.get("fund_info")
    
    if not raw_report_data:
        fallback = "<p>Error: No fund data could be retrieved or analyzed. Please check your inputs and try again.</p>"
        return {"tool_result": fallback}

    # Pass the raw analysis to the LLM to format it beautifully
    instruction = f"Format the following AI analysis into the final HTML report structure:\n\n{raw_report_data}"
    
    response = llm.invoke([
        ("system", SYNTH_PROMPT),
        ("human", instruction),
    ])

    cleaned_html = clean_html_output(response.content)

    return {"tool_result": cleaned_html}